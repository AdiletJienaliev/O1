using UnityEngine;

namespace Warlord.Presentation.Animation
{
    /// <summary>
    /// Точки входа анимации персонажа — и полководца, и юнита. Геймплей вызывает эти методы,
    /// не зная ничего про Animator: сейчас клипов ещё нет, и реализация просто молчит,
    /// но вызовы уже стоят в правильных местах и обвязку менять не придётся.
    ///
    /// Всё, что здесь есть, — чистая презентация. Ни один вызов не влияет на симуляцию,
    /// поэтому дёргать их можно с частотой кадров и только на клиентах.
    /// </summary>
    public interface ICharacterAnimation
    {
        /// <summary>
        /// Передвижение. <paramref name="localDirection"/> — направление шага в осях самого
        /// персонажа (x — вбок, y — вперёд), единичной длины: именно оно кормит двумерный
        /// blend tree и позволяет стрейфу выглядеть стрейфом, а не бегом боком.
        /// <paramref name="speed01"/> — доля от скорости бега, 0..1: по ней выбирается
        /// стойка, шаг или бег.
        ///
        /// Длина и величина разведены намеренно. Держи их в одном векторе — и шаг вбок,
        /// вдвое более медленный, чем бег, читался бы аниматором как «полушага вбок»,
        /// то есть как смесь ходьбы со стойкой, а не как честный приставной шаг.
        /// </summary>
        void SetLocomotion(Vector2 localDirection, float speed01);

        /// <summary>Стоит ли персонаж на земле. Для юнитов всегда true.</summary>
        void SetGrounded(bool grounded);

        void PlayJump();

        /// <summary>
        /// Щит поднят или опущен (ГДД §6, приказ «Защита»). Состояние, а не событие:
        /// поза держится ровно столько, сколько действует приказ.
        /// </summary>
        void SetDefending(bool defending);

        /// <summary>Удар принят на щит: дрогнувшая стойка. Урона за этим нет.</summary>
        void PlayBlockImpact();

        /// <summary>Замах. Вызывается в момент удара, а не в момент нанесения урона.</summary>
        void PlayAttack();

        void PlayDeath();

        /// <summary>Возврат в строй после смерти: сбрасывает позу смерти.</summary>
        void PlayRespawn();
    }
}
